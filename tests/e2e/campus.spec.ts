test('BFF denies cross-origin writes and never exposes access tokens',async({request})=>{
  const denied=await request.post('/api/auth/demo',{data:{user_id:'20000000-0000-4000-8000-000000000001'},headers:{origin:'https://foreign.example'}});
  expect(denied.status()).toBe(403);
  const allowed=await request.post('/api/auth/demo',{data:{user_id:'20000000-0000-4000-8000-000000000001'},headers:{origin:TEST_ORIGIN}});
  expect(allowed.ok()).toBeTruthy();
  expect(await allowed.json()).toEqual({authenticated:true});
  expect(allowed.headers()['set-cookie']).toContain('HttpOnly');
  expect(allowed.headers()['set-cookie']).toContain('SameSite=strict');
});
