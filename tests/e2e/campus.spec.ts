import { test,expect } from '@playwright/test';
import { TEST_ORIGIN } from './test-origin';
test('administration: login, real creation, search, persistence and logout',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:/Amira Ben Ali/}).click();
  await page.getByRole('button',{name:'Vue d’ensemble',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Bonjour, Amira/})).toBeVisible();
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Structure universitaire',exact:true}).click();
  await page.getByRole('button',{name:'Ajouter un département'}).click();
  const name=`Département test ${Date.now()}`;
  await page.getByLabel('Nom',{exact:true}).fill(name);
  await page.getByLabel('Code',{exact:true}).fill(`TEST-${Date.now()}`);
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('textbox',{name:'Rechercher dans Départements'}).fill(name);
  await expect(page.getByRole('cell',{name,exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading',{name:'Devoirs & examens',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Structure universitaire',exact:true}).click();
  await page.getByRole('textbox',{name:'Rechercher dans Départements'}).fill(name);
  await expect(page.getByRole('cell',{name,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Mon profil',exact:true}).click();
  await page.getByRole('button',{name:'Se déconnecter',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Votre campus commence ici.'})).toBeVisible();
});
